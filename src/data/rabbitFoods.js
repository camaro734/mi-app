// Función para buscar alimentos por nombre o keyword
export function searchFoods(query) {
  if (!query || query.trim().length === 0) return [];
  const normalizedQuery = query.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  return rabbitFoods.filter((food) => {
    const normalizedName = food.name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    const normalizedKeywords = food.keywords.map((k) =>
      k.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    );
    return (
      normalizedName.includes(normalizedQuery) ||
      normalizedKeywords.some((k) => k.includes(normalizedQuery))
    );
  });
}

// Obtener alimentos por categoría
export function getFoodsByCategory(category) {
  return rabbitFoods.filter((food) => food.category === category);
}

// Obtener alimentos por nivel de seguridad
export function getFoodsBySafety(safety) {
  return rabbitFoods.filter((food) => food.safety === safety);
}

// Obtener un alimento por ID
export function getFoodById(id) {
  return rabbitFoods.find((food) => food.id === id);
}

// Estadísticas
export function getStats() {
  return {
    total: rabbitFoods.length,
    safe: rabbitFoods.filter((f) => f.safety === 'safe').length,
    caution: rabbitFoods.filter((f) => f.safety === 'caution').length,
    dangerous: rabbitFoods.filter((f) => f.safety === 'dangerous').length,
  };
}
